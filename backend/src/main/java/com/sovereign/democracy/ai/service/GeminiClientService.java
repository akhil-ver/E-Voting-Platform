package com.sovereign.democracy.ai.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.sovereign.democracy.ai.config.GeminiConfig;
import com.sovereign.democracy.ai.dto.GeminiRequestDto;
import com.sovereign.democracy.ai.dto.GeminiResponseDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestClient;

import java.time.Instant;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;

@Service
public class GeminiClientService {

    private static final Logger log = LoggerFactory.getLogger(GeminiClientService.class);

    private final GeminiConfig geminiConfig;
    private final RestClient geminiRestClient;
    private final ObjectMapper objectMapper;

    // Rate limiting tracking
    private final AtomicInteger requestCounter = new AtomicInteger(0);
    private volatile long currentMinuteWindow = Instant.now().getEpochSecond() / 60;

    // Simple in-memory response cache with 5-minute TTL
    private final Map<String, CacheEntry> responseCache = new ConcurrentHashMap<>();
    private static final long CACHE_TTL_SECONDS = 300; // 5 minutes

    public GeminiClientService(GeminiConfig geminiConfig, RestClient geminiRestClient, ObjectMapper objectMapper) {
        this.geminiConfig = geminiConfig;
        this.geminiRestClient = geminiRestClient;
        this.objectMapper = objectMapper;
    }

    /**
     * Executes prompt against Google Gemini API with rate limiting, caching, and safe error handling.
     *
     * @param prompt User/system prompt
     * @param maxTokens Sensible token ceiling
     * @param temperature Output temperature
     * @return Optional text generated by model, or empty if offline / rate-limited / error
     */
    public boolean isEnabled() {
        return geminiConfig.isEnabled();
    }

    public Optional<String> generateContent(String prompt) {
        return generateContent(prompt, 1024, 0.2);
    }

    public Optional<String> generateContent(String prompt, Integer maxTokens, Double temperature) {
        if (!geminiConfig.isEnabled()) {
            log.info("Gemini AI integration is disabled or no API key is configured. Returning offline fallback.");
            return Optional.empty();
        }

        if (prompt == null || prompt.trim().isEmpty()) {
            return Optional.empty();
        }

        // Cache lookup
        String cacheKey = computeCacheKey(prompt, geminiConfig.getModel());
        CacheEntry cached = responseCache.get(cacheKey);
        if (cached != null && !cached.isExpired()) {
            log.debug("Serving Gemini AI response from memory cache for prompt hash {}", cacheKey.hashCode());
            return Optional.of(cached.text);
        }

        // Rate limiting check
        if (!allowRequest()) {
            log.warn("Gemini API client rate limit exceeded ({} req/min). Falling back to deterministic summary.",
                    geminiConfig.getRateLimitPerMinute());
            return Optional.empty();
        }

        try {
            int tokenCeiling = maxTokens != null ? Math.min(maxTokens, 2048) : 1024;
            double temp = temperature != null ? Math.max(0.0, Math.min(temperature, 1.0)) : 0.2;

            GeminiRequestDto requestDto = new GeminiRequestDto(prompt, tokenCeiling, temp);

            String uri = String.format("/models/%s:generateContent?key=%s",
                    geminiConfig.getModel(), geminiConfig.getApiKey());

            GeminiResponseDto response = geminiRestClient.post()
                    .uri(uri)
                    .contentType(MediaType.APPLICATION_JSON)
                    .body(requestDto)
                    .retrieve()
                    .body(GeminiResponseDto.class);

            if (response != null && response.getFirstText() != null) {
                String generatedText = response.getFirstText().trim();
                // Store in cache
                responseCache.put(cacheKey, new CacheEntry(generatedText, Instant.now().getEpochSecond()));
                log.info("Successfully received Gemini AI response using model: {}", geminiConfig.getModel());
                return Optional.of(generatedText);
            }

            log.warn("Gemini API returned empty response candidates");
            return Optional.empty();
        } catch (Exception e) {
            log.warn("Gemini AI request failed: {}. Continuing with deterministic fallback.", e.getMessage());
            return Optional.empty();
        }
    }

    private synchronized boolean allowRequest() {
        long nowMinute = Instant.now().getEpochSecond() / 60;
        if (nowMinute != currentMinuteWindow) {
            currentMinuteWindow = nowMinute;
            requestCounter.set(0);
        }
        return requestCounter.incrementAndGet() <= geminiConfig.getRateLimitPerMinute();
    }

    private String computeCacheKey(String prompt, String model) {
        return model + "::" + prompt.trim().hashCode();
    }

    public boolean isConfigured() {
        return geminiConfig.isEnabled();
    }

    public String getConfiguredModel() {
        return geminiConfig.getModel();
    }

    private static class CacheEntry {
        final String text;
        final long createdAtSeconds;

        CacheEntry(String text, long createdAtSeconds) {
            this.text = text;
            this.createdAtSeconds = createdAtSeconds;
        }

        boolean isExpired() {
            return (Instant.now().getEpochSecond() - createdAtSeconds) > CACHE_TTL_SECONDS;
        }
    }
}
